def distil_window_cells(row):
    """Innermost generator: yields from nested loops and a genexp."""
    for i, v in enumerate(row):
        if v % 2:
            yield from (v * k for k in range(1, 3) if v * k < 64)
        else:
            for k in range(2):
                if v + k:
                    yield v + k


def distil_window_rows(matrix):
    for row in matrix:
        if row:
            yield from distil_window_cells(row)


def distil_window(matrix):
    acc, runs = [], []
    streak = 0
    for v in distil_window_rows(matrix):
        if v % 3 == 0:
            streak += 1
            if streak > 2:
                runs.append(streak)
                streak = 0
        else:
            if streak:
                runs.append(-streak)
            streak = 0
            if len(acc) < 32:
                acc.append(v)
    return {"acc": acc[:8], "runs": runs[:8], "streak": streak}


