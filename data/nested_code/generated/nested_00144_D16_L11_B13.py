def rank_channel_pong(node, budget=4):
    if budget <= 0:
        return 0
    acc = 0
    for child in (node.get("children") or [])[:2]:
        if isinstance(child, dict):
            if budget % 2 == 0:
                acc += rank_channel_ping(child, budget - 1)
            else:
                acc += rank_channel_pong(child, budget - 1)
    return acc + 1


