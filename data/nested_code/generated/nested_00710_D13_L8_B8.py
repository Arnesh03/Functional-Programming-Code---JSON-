def fold_matrix_cells(row):
    """Innermost generator: yields from nested loops and a genexp."""
    for i, v in enumerate(row):
        if v % 2:
            yield from (v * k for k in range(1, 3) if v * k < 64)
        else:
            for k in range(2):
                if v + k:
                    yield v + k


def fold_matrix_rows(matrix):
    for row in matrix:
        if row:
            yield from fold_matrix_cells(row)


