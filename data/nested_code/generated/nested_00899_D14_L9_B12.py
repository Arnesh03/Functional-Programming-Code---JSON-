def splice_cohort(seed=3):
    """Functions nested 4 deep, each closing over every level above it."""
    def level0(a0):
        if a0 % 2:
            a0 += 1
        def level1(a1):
            if a1 % 2:
                a1 += 2
            def level2(a2):
                if a2 % 2:
                    a2 += 3
                def level3(a3):
                    if a3 % 2:
                        a3 += 4
                    acc = 0
                    for step in range(3):
                        if step % 2 == 0:
                            acc += a0 + a1 + a2 + a3
                        else:
                            acc -= step
                    return acc
                return level3
            return level2
        return level1
    chain = level0
    return level0(seed + 0)(seed + 1)(seed + 2)(seed + 3) + (0 if chain else 1)


def merge_graph_cells(row):
    """Innermost generator: yields from nested loops and a genexp."""
    for i, v in enumerate(row):
        if v % 2:
            yield from (v * k for k in range(1, 3) if v * k < 64)
        else:
            for k in range(2):
                if v + k:
                    yield v + k


def merge_graph_rows(matrix):
    for row in matrix:
        if row:
            yield from merge_graph_cells(row)


