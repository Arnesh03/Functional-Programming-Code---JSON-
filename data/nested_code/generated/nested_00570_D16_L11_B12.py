def chart_lattice(seed=3):
    """Functions nested 5 deep, each closing over every level above it."""
    def level0(a0):
        if a0 % 2:
            a0 += 1
        def level1(a1):
            if a1 % 2:
                a1 += 2
            def level2(a2):
                if a2 % 2:
                    a2 += 3
                def level3(a3):
                    if a3 % 2:
                        a3 += 4
                    def level4(a4):
                        if a4 % 2:
                            a4 += 5
                        acc = 0
                        for step in range(3):
                            if step % 2 == 0:
                                acc += a0 + a1 + a2 + a3 + a4
                            else:
                                acc -= step
                        return acc
